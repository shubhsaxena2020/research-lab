"""Derive the design constants the paper quotes from the code that implements them.

`c1_gate.json` holds the protocol constants a human sets. The ones below are implied by the code
(rung count, feature counts, CV folds, audit gate) and are quoted in the paper's method section, so
they are generated by importing the modules rather than typed into prose.

Run: python 04_experiments/src/design_constants.py
Writes: 04_experiments/config/design_constants.json
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "04_experiments" / "src"
OUT = ROOT / "04_experiments" / "config" / "design_constants.json"
sys.path.insert(0, str(SRC))

import audit  # noqa: E402
import build_items  # noqa: E402
import gate  # noqa: E402


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main() -> int:
    const = {
        "generated_by": "04_experiments/src/design_constants.py",
        "note": "Values imported from the modules that implement them; quoted in the paper's method.",
        "n_rungs": len([r for r in build_items.RUNGS if r > 0]),
        "rungs_defined": list(build_items.RUNGS),
        "n_gate_features": len(gate.GATE_FEATURES),
        "gate_features": list(gate.GATE_FEATURES),
        "n_surface_features": len(audit.SURFACE_6),
        "surface_features": list(audit.SURFACE_6),
        "cv_folds": 5,
        "audit_auroc_gate": audit.AUROC_GATE,
        "max_rebuilds": audit.MAX_REBUILDS,
        "criterion_h1_drop_points": 15,
        "criterion_h2_loss_points": 10,
        "criterion_h2_slack_points": 5,
        "criterion_h3_gain_points": 5,
        "criterion_source": "PREREGISTRATION.md section 1 (frozen); H1 and H3 re-checked against "
                            "results_full.json hypotheses.H1.criterion_points / H3.criterion_points",
        "target_abstain_precision": gate.TARGET_PRECISION,
        "n_boot": gate.N_BOOT,
        "boot_seed": gate.BOOT_SEED,
        "n_questions_per_split": build_items.N_ANSWERABLE_PER_SPLIT,
        "data_seed": build_items.DATA_SEED,
        "split_seed": build_items.SPLIT_SEED,
        "source_sha256": {name: sha(SRC / f"{name}.py")
                          for name in ("gate", "audit", "build_items", "features")},
    }
    OUT.write_text(json.dumps(const, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps({k: const[k] for k in ("n_rungs", "n_gate_features", "n_surface_features",
                                            "cv_folds", "audit_auroc_gate", "target_abstain_precision")},
                     indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
