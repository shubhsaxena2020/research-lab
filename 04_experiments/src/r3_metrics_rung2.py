"""R3-1 metrics: held-out rung-2 shortfall + exchangeability on BOTH splits (MF-22)."""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "04_experiments" / "src"
DATA = ROOT / "04_experiments" / "data"
RESULTS = ROOT / "04_experiments" / "results" / "c1"
R3METRICS = RESULTS / "r3" / "metrics"
REPORT = ROOT / "sessions" / "R3-1-metrics" / "reports" / "r3_metrics_rung2.md"

sys.path.insert(0, str(SRC))
import stats_addendum as SA

SEED = 12345
N_BOOT = 10000
COMMAND = "python 04_experiments/src/r3_metrics_rung2.py"
VARIABLES = ("q_chars", "q_tokens", "gold_chars", "n_paragraphs", "answer_type")


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def fmt_p(p):
    if p is None:
        return "n/a"
    if p < 1e-3:
        return "<0.001"
    return f"{p:.3f}"


def load_items():
    with open(DATA / "items.jsonl", encoding="utf-8") as fh:
        return [json.loads(line) for line in fh if line.strip()]


def main() -> None:
    items = load_items()
    ex = SA.exchangeability(items)

    splits_out = {}
    for split in ("dev", "test"):
        blk = ex["splits"][split]
        pvals = {}
        for v in VARIABLES:
            d = blk["variables"][v]
            pvals[v] = d["p_value"]
        splits_out[split] = {
            "n_sampled": 400,
            "n_kept": blk["n_kept"],
            "n_dropped": blk["n_dropped"],
            "share_kept": blk["share_kept"],
            "p_values": pvals,
            "variables": blk["variables"],
        }

    held = splits_out["test"]
    min_p = ex["min_p"]

    result = {
        "generated_by": "04_experiments/src/r3_metrics_rung2.py",
        "command": COMMAND,
        "seed": SEED,
        "n_boot": N_BOOT,
        "held_out_split": "test",
        "shortfall": {
            "population": 400,
            "kept": held["n_kept"],
            "dropped": held["n_dropped"],
            "reason": "no_anchor_candidate",
        },
        "n_kept": held["n_kept"],
        "n_dropped": held["n_dropped"],
        "p_values": {s: splits_out[s]["p_values"] for s in ("dev", "test")},
        "per_split": splits_out,
        "splits": splits_out,
        "exchangeability": ex,
        "min_p": min_p,
        "verdict": ex["verdict"],
        "significant_at_0.05": ex.get("significant_at_0.05"),
        "inputs": {
            "items_jsonl": sha256(DATA / "items.jsonl"),
            "dev_v2_0_json": sha256(DATA / "raw" / "dev-v2.0.json"),
            "build_items_py": sha256(SRC / "build_items.py"),
            "stats_addendum_py": sha256(SRC / "stats_addendum.py"),
        },
    }

    R3METRICS.mkdir(parents=True, exist_ok=True)
    out_json = R3METRICS / "rung2.json"
    out_json.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    lines = []
    A = lines.append
    A("# R3 metrics — rung-2 held-out shortfall and exchangeability (MF-22)\n")
    A("Generated by `04_experiments/src/r3_metrics_rung2.py` (command: `%s`). "
      "Seed %d, %d permutation draws. Every number below is read from "
      "`04_experiments/results/c1/r3/metrics/rung2.json`.\n" % (COMMAND, SEED, N_BOOT))
    A("## Held-out rung-2 shortfall\n")
    A("Rung 2 keeps only questions that have an anchor candidate in a non-gold paragraph. "
      "On the held-out (test) split this keeps **%d of 400** and drops **%d**; on dev it keeps "
      "**%d of 400** and drops **%d**. The shortfall is the reason rung-2 cells have smaller n.\n"
      % (held["n_kept"], held["n_dropped"], splits_out["dev"]["n_kept"], splits_out["dev"]["n_dropped"]))
    A("| Split | Sampled | Kept | Dropped | Share kept |")
    A("|---|---:|---:|---:|---:|")
    for split in ("dev", "test"):
        b = splits_out[split]
        A("| %s | %d | %d | %d | %.1f%% |" % (split, b["n_sampled"], b["n_kept"], b["n_dropped"],
                                                100 * b["share_kept"]))
    A("")
    A("## Exchangeability (kept vs dropped), both splits\n")
    A("Method: same as `stats_addendum.exchangeability` — two-sided Mann-Whitney U "
      "(no continuity correction) on q_chars, q_tokens, gold_chars, n_paragraphs; "
      "answer-type 5x2 table via Pearson chi-square, or a Monte Carlo permutation "
      "(10,000 draws, seed %d) when any expected cell < 5.\n" % SEED)
    for split in ("dev", "test"):
        b = splits_out[split]
        A("### %s: %d kept vs %d dropped\n" % (split, b["n_kept"], b["n_dropped"]))
        A("| Variable | p-value |")
        A("|---|---:|")
        for v in VARIABLES:
            p = b["p_values"][v]
            A("| %s | %s |" % (v, fmt_p(p)))
        A("")
    A("**Verdict.** " + ex["verdict"] + "\n")
    A("Smallest p across both splits: %s (%s). Significant at 0.05: %s.\n"
      % (fmt_p(min_p["value"]), min_p["variable"],
         ", ".join(ex.get("significant_at_0.05") or []) or "none"))
    A("---")
    A("_Inputs (sha256): items.jsonl `%s...`._\n" % result["inputs"]["items_jsonl"][:16])

    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(json.dumps({
        "wrote": [str(out_json), str(REPORT)],
        "held_out_kept": held["n_kept"],
        "held_out_dropped": held["n_dropped"],
        "dev_kept": splits_out["dev"]["n_kept"],
        "dev_dropped": splits_out["dev"]["n_dropped"],
        "p_values": result["p_values"],
        "min_p": min_p,
        "verdict": ex["verdict"],
    }, indent=2))


if __name__ == "__main__":
    main()
