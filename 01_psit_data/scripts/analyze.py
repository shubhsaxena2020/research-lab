#!/usr/bin/env python
"""Analysis of 01_psit_data/papers.csv -> analysis/tables/*.md|.csv + analysis/numbers.json

Every number in the write-up must be traceable to a key in numbers.json, and every
key must be reproducible by re-running this script on the same papers.csv.

Design choices that matter for honesty:
- "year" is the Crossref/Europe PMC issued year; 2026 is a partial year (data
  retrieved 2026-11-03), so year trends must be read with that caveat.
- Citation counts come from Crossref's is-referenced-by-count (a lower bound; it
  only counts citations from DOI-registered works). It is NOT OpenAlex or Scopus.
- Topic tags are keyword heuristics (see build_dataset.py TOPIC_RULES), not a
  database subject classification.
- Anything that needs a subscription (Scopus/WoS indexing, JCR quartiles) is
  reported as UNAVAILABLE rather than guessed.
"""
import csv
import json
import os
import re
import statistics
import time
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAPERS = os.path.join(ROOT, "papers.csv")
OUT = os.path.join(ROOT, "analysis")
TAB = os.path.join(OUT, "tables")
os.makedirs(TAB, exist_ok=True)

PSIT_RE = re.compile(r"PSIT|Pranveer\s*Singh", re.I)


def load():
    with open(PAPERS, encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def write_table(name, header, rows, title, note=""):
    md = ["# %s" % title, "", note, "" if note else None,
          "| " + " | ".join(header) + " |",
          "|" + "|".join(["---"] * len(header)) + "|"]
    md = [x for x in md if x is not None]
    for r in rows:
        md.append("| " + " | ".join(str(c) for c in r) + " |")
    md.append("")
    md.append("Generated by 01_psit_data/scripts/analyze.py from papers.csv on "
              + time.strftime("%Y-%m-%d"))
    with open(os.path.join(TAB, name + ".md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(md))
    with open(os.path.join(TAB, name + ".csv"), "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(header)
        w.writerows(rows)


def main():
    rows = load()
    N = len(rows)
    num = {"n_records": N, "generated": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
           "source_file": "01_psit_data/papers.csv"}

    years = Counter(int(r["year"]) for r in rows if r["year"])
    num["year_counts"] = dict(sorted(years.items()))
    num["year_min"], num["year_max"] = min(years), max(years)
    num["year_2026_is_partial"] = True
    write_table("papers-per-year", ["year", "papers"],
                [[y, c] for y, c in sorted(years.items())],
                "Papers per year (PSIT affiliation, all sources)",
                "Year = issued year as deposited in Crossref/Europe PMC. 2026 is a "
                "partial year: data retrieved 2026-11-03.")

    types = Counter(r["type"] or "unknown" for r in rows)
    num["type_counts"] = dict(types.most_common())
    write_table("document-types", ["type", "papers", "share_%"],
                [[t, c, round(100.0 * c / N, 1)] for t, c in types.most_common()],
                "Document types", "Type as declared to Crossref.")

    # --- AI share ------------------------------------------------------
    ai_year = defaultdict(lambda: [0, 0])
    for r in rows:
        if not r["year"]:
            continue
        y = int(r["year"])
        ai_year[y][1] += 1
        if r["ai_related"] == "yes":
            ai_year[y][0] += 1
    num["ai_related_total"] = sum(1 for r in rows if r["ai_related"] == "yes")
    num["ai_related_share_pct"] = round(100.0 * num["ai_related_total"] / N, 1)
    num["ai_by_year"] = {y: {"ai": v[0], "total": v[1],
                             "share_pct": round(100.0 * v[0] / v[1], 1)}
                         for y, v in sorted(ai_year.items())}
    write_table("ai-share-by-year", ["year", "ai_related", "all", "share_%"],
                [[y, v[0], v[1], round(100.0 * v[0] / v[1], 1)] for y, v in sorted(ai_year.items())],
                "AI/ML-related share by year",
                "ai_related=yes means the title or abstract contains a strict AI/ML term "
                "(list in build_dataset.py AI_STRICT_RE). Keyword heuristic, not a subject "
                "classification.")

    # --- topics --------------------------------------------------------
    topic_counts = Counter()
    first_topic = Counter()
    for r in rows:
        tags = [t for t in (r["topics"] or "").split(";") if t and t != "untagged"]
        if not tags:
            first_topic["untagged"] += 1
            continue
        first_topic[tags[0]] += 1
        for t in tags:
            topic_counts[t] += 1
    num["topic_counts_multilabel"] = dict(topic_counts.most_common())
    num["topic_counts_primary"] = dict(first_topic.most_common())
    write_table("topics", ["topic", "papers(any tag)", "papers(primary tag)"],
                [[t, c, first_topic.get(t, 0)] for t, c in topic_counts.most_common()]
                + ([["untagged", 0, first_topic["untagged"]]] if first_topic["untagged"] else []),
                "Topic distribution (keyword heuristic)",
                "A paper can carry several tags, so the multi-label column sums to more "
                "than the record count. Primary tag = first rule that matched.")

    # --- venues --------------------------------------------------------
    venues = Counter()
    for r in rows:
        v = (r["venue"] or "").strip()
        if v:
            venues[v[:90]] += 1
    num["distinct_venues"] = len(venues)
    num["venues_with_1_paper"] = sum(1 for c in venues.values() if c == 1)
    write_table("top-venues", ["venue", "papers"],
                [[v, c] for v, c in venues.most_common(40)],
                "Top 40 venues by paper count",
                "Venue string as deposited. Journal and conference names are not "
                "normalised, so near-duplicates can appear as separate rows.")

    # --- authors -------------------------------------------------------
    author_counts = Counter()
    psit_author_counts = Counter()
    for r in rows:
        for a in (r["authors"] or "").split(";"):
            a = a.strip()
            if a and len(a) > 3:
                author_counts[a] += 1
        for a in (r["psit_authors"] or "").split(";"):
            a = a.strip()
            if a and len(a) > 3:
                psit_author_counts[a] += 1
    num["distinct_authors_all"] = len(author_counts)
    num["distinct_psit_authors"] = len(psit_author_counts)
    num["authors_with_10plus"] = sum(1 for c in psit_author_counts.values() if c >= 10)
    write_table("top-psit-authors", ["author", "papers with PSIT affiliation string"],
                [[a, c] for a, c in psit_author_counts.most_common(40)],
                "Most prolific authors carrying a PSIT affiliation string",
                "Name strings as deposited; homonyms and spelling variants are not "
                "disambiguated, so treat ranks as approximate.")

    # --- citations -----------------------------------------------------
    cites = []
    for r in rows:
        try:
            cites.append(int(float(r["cited_by"])))
        except (TypeError, ValueError):
            pass
    cites_sorted = sorted(cites, reverse=True)
    num["citation_records_with_count"] = len(cites)
    num["citations_total"] = sum(cites)
    num["citations_mean"] = round(statistics.mean(cites), 2) if cites else None
    num["citations_median"] = statistics.median(cites) if cites else None
    num["citations_zero_share_pct"] = round(100.0 * sum(1 for c in cites if c == 0) / len(cites), 1) if cites else None
    if cites_sorted:
        for q in (50, 75, 90, 95, 99):
            num["citations_p%d" % q] = cites_sorted[int(len(cites_sorted) * (100 - q) / 100)]
    write_table("citation-distribution", ["statistic", "value"], [
        ["records with a citation count", len(cites)],
        ["total citations (Crossref)", num["citations_total"]],
        ["mean", num["citations_mean"]],
        ["median", num["citations_median"]],
        ["share with zero citations (%)", num["citations_zero_share_pct"]],
        ["p90", num.get("citations_p90")],
        ["p99", num.get("citations_p99")],
        ["max", cites_sorted[0] if cites_sorted else None],
    ], "Citation distribution (Crossref is-referenced-by-count)",
        "Crossref counts only citations from DOI-registered works, so this is a lower "
        "bound and is not comparable to OpenAlex or Scopus counts.")

    top_cited = sorted([r for r in rows if (r["cited_by"] or "").isdigit()],
                       key=lambda r: int(r["cited_by"]), reverse=True)[:20]
    write_table("top-cited", ["citations", "year", "title", "venue", "doi"],
                [[r["cited_by"], r["year"], r["title"][:90], (r["venue"] or "")[:60], r["doi"]]
                 for r in top_cited],
                "20 most-cited papers in the dataset",
                "Crossref counts only. Do not present as 'citation impact' without saying so.")

    # --- collaboration -------------------------------------------------
    n_auth = []
    for r in rows:
        try:
            n_auth.append(int(r["n_authors"]))
        except (TypeError, ValueError):
            pass
    num["authors_per_paper_median"] = statistics.median(n_auth) if n_auth else None
    num["authors_per_paper_mean"] = round(statistics.mean(n_auth), 2) if n_auth else None
    num["single_author_papers"] = sum(1 for x in n_auth if x == 1)
    num["papers_6plus_authors"] = sum(1 for x in n_auth if x >= 6)

    # --- affiliation vocabulary (institutional identity evidence) --------
    affil = Counter()
    for r in rows:
        for a in (r["affiliations"] or "").split("|"):
            a = re.sub(r"\s+", " ", a).strip().strip(".,;")
            if a and PSIT_RE.search(a):
                affil[a] += 1
    buckets = {"mentions_PSIT_abbrev": 0, "mentions_Pranveer": 0,
               "mentions_higher_education": 0, "mentions_pharmacy": 0,
               "mentions_kanpur": 0}
    for a, c in affil.items():
        if re.search(r"\bPSIT\b", a, re.I):
            buckets["mentions_PSIT_abbrev"] += c
        if re.search(r"Pranveer", a, re.I):
            buckets["mentions_Pranveer"] += c
        if re.search(r"higher education", a, re.I):
            buckets["mentions_higher_education"] += c
        if re.search(r"pharmac", a, re.I):
            buckets["mentions_pharmacy"] += c
        if re.search(r"kanpur", a, re.I):
            buckets["mentions_kanpur"] += c
    # Two distinct record-level counts, named explicitly to avoid ambiguity:
    #   records_with_affil_text_nonempty - any deposited affiliation text at all
    #   records_with_psit_affil_string   - at least one affiliation string naming PSIT
    buckets["records_with_affil_text_nonempty"] = sum(
        1 for r in rows if (r["affiliations"] or "").strip())
    buckets["records_with_psit_affil_string"] = sum(
        1 for r in rows if PSIT_RE.search(r["affiliations"] or ""))
    num["affiliation_strings_distinct"] = len(affil)
    num["affiliation_buckets"] = buckets
    write_table("affiliation-vocabulary", ["affiliation string (PSIT only)", "papers"],
                [[a[:110], c] for a, c in affil.most_common(40)],
                "How PSIT is written in deposited affiliations (top 40)",
                "This is the evidence base for the institutional-identity question: which "
                "names in the literature refer to PSIT-Pharmacy, PSIT-CHE, or PSIT generally.")

    # --- sources / coverage -------------------------------------------
    src = Counter(r["source"] for r in rows)
    num["source_counts"] = dict(src.most_common())
    in_dblp = sum(1 for r in rows if r.get("in_dblp") == "yes")
    num["in_dblp_yes"] = in_dblp
    num["in_dblp_checked"] = sum(1 for r in rows if r.get("in_dblp") in ("yes", "no"))

    with open(os.path.join(OUT, "numbers.json"), "w", encoding="utf-8") as fh:
        json.dump(num, fh, indent=1)
    print(json.dumps({k: num[k] for k in
                      ("n_records", "ai_related_total", "ai_related_share_pct",
                        "distinct_venues", "citations_total", "citations_median",
                        "distinct_psit_authors", "in_dblp_yes", "in_dblp_checked")}, indent=1))
    print("tables ->", TAB)


if __name__ == "__main__":
    main()
